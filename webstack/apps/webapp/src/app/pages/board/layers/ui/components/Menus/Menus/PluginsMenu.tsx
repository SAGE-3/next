import { useRef, useState } from 'react';
import {
  useColorModeValue,
  VStack,
  Box,
  Badge,
  Text,
  Divider,
  useDisclosure,
  Button,
  HStack,
  Modal,
  ModalOverlay,
  ModalContent,
  ModalHeader,
  ModalBody,
  ModalFooter,
  UnorderedList,
  ListItem,
  useToast,
  Checkbox,
} from '@chakra-ui/react';
import type { Plugin } from '@sage3/shared/types';
import type { PluginCapability } from '@sage3/sageplugin';
import { EnabledPlugin, isPluginEnabled, PluginActions, PluginUploadModal, usePluginStore, useRoomStore, useUser } from '@sage3/frontend';

const capabilityLabels: Readonly<Record<PluginCapability, string>> = {
  'apps.read': 'Read apps, shared app text, and app paint order on this board',
  'apps.write': 'Create, change, and remove apps on this board',
  'links.read': 'Read links between apps on this board',
  'links.write': 'Create and remove links between apps on this board',
  'annotations.read': 'Read drawings on this board',
  'documents.read': 'Read document assets, text, and selections on this board',
  'documents.navigate': 'Change document pages for everyone on this board',
  'assets.read': 'Read and download files in this room',
  'assets.write': 'Upload files to this room',
  'urls.open': 'Request that you open external websites',
  'downloads.write': 'Request that you save files generated by this extension',
};

export interface PluginsMenuProps {
  readonly boardId: string;
  readonly roomId: string;
  readonly onActionComplete?: () => void;
  readonly target?: { x: number; y: number };
}

/** Board-scoped approval and explicit commands for room plugins. */
export function PluginsMenu(props: PluginsMenuProps) {
  // Plugin store. Sort them by name.
  const allPlugins = usePluginStore((state) => state.plugins);
  const plugins = allPlugins.filter((plugin) => plugin.data.roomId === props.roomId);
  plugins.sort((firstPlugin, secondPlugin) => firstPlugin.data.name.localeCompare(secondPlugin.data.name));

  // User
  const { user } = useUser();
  const room = useRoomStore((state) => state.rooms.find((entry) => entry._id === props.roomId));
  const isRoomOwner = !!user && room?.data.ownerId === user._id;
  const setEnabled = usePluginStore((state) => state.setEnabled);
  const [approval, setApproval] = useState<Plugin | null>(null);
  const [autoApprove, setAutoApprove] = useState(false);
  const [pending, setPending] = useState<string | null>(null);
  const denyRef = useRef<HTMLButtonElement>(null);
  const toast = useToast();

  // Colors
  const gripColor = useColorModeValue('#c1c1c1', '#2b2b2b');

  const { isOpen: pluginIsOpen, onOpen: pluginOnOpen, onClose: pluginOnClose } = useDisclosure();

  const openApproval = (plugin: Plugin) => {
    const policy = plugin.data.boardAutoApprovals?.[props.boardId];

    setAutoApprove(
      !!policy &&
        policy.ownerId === user?._id &&
        !!plugin.data.package?.manifest.capabilities.every((capability) => policy.capabilities.includes(capability)),
    );
    setApproval(plugin);
  };

  // Activation controls are shown to the room owner only and disabled while a change is pending.
  // Enabling happens only from the approval modal, which opens only for a packaged plugin.
  const changeActivation = async (plugin: Plugin, enabled: boolean) => {
    setPending(plugin._id);

    try {
      const result = await setEnabled(
        plugin._id,
        props.boardId,
        enabled ? { enabled: true, packageDigest: (plugin as EnabledPlugin).data.package.digest, autoApprove } : { enabled: false },
      );

      let activationTitle: string;
      let activationDescription: string | undefined;

      if (result.success) {
        activationTitle = enabled ? 'Plugin enabled' : 'Plugin disabled';
        activationDescription = enabled
          ? result.message
          : 'Future upload approval is off. Existing apps and saved data have been preserved.';
      } else {
        activationTitle = 'Plugin activation failed';
        activationDescription = `${result.message ?? 'Activation failed.'} Reopen Enable to review the current package.`;
      }

      toast({
        title: activationTitle,
        description: activationDescription,
        status: result.success ? 'success' : 'error',
        isClosable: true,
    });

      setApproval(null);
    } finally {
      setPending(null);
    }
  };

  return (
    <>
      <PluginUploadModal isOpen={pluginIsOpen} onOpen={pluginOnOpen} onClose={pluginOnClose} roomId={props.roomId} />
      <Modal
        isOpen={!!approval?.data.package}
        onClose={() => {
          if (!pending) {
            setApproval(null);
          }
        }}
        initialFocusRef={denyRef}
        isCentered
      >
        <ModalOverlay />
        <ModalContent>
          <ModalHeader>Enable {approval?.data.package?.manifest.name}?</ModalHeader>
          <ModalBody>
            <Text mb="3">This plugin will run for participants on this board with these capabilities:</Text>
            {approval?.data.package?.manifest.capabilities.length ? (
              <UnorderedList>
                {approval.data.package.manifest.capabilities.map((capability) => (
                  <ListItem key={capability}>{capabilityLabels[capability]}</ListItem>
                ))}
              </UnorderedList>
            ) : (
              <Text>No additional capabilities requested.</Text>
            )}
            <Text mt="3">
              Plugins can always save their own state and app content. Disable at any time without deleting apps or saved data.
            </Text>
            <Text mt="3" fontWeight="bold">
              Read permissions expose board and document data to extension code. Only approve packages you trust.
            </Text>
            <Checkbox
              mt="4"
              isChecked={autoApprove}
              isDisabled={!!pending || !isRoomOwner}
              onChange={(event) => setAutoApprove(event.target.checked)}
            >
              Auto-approve future uploads by {approval?.data.ownerName || 'this plugin’s uploader'} on this board within these capabilities.
            </Checkbox>
            <Text mt="2" fontSize="sm">
              This trusts future code from this uploader, not just the reviewed package. Updates may run for everyone without another
              prompt. New capabilities or a room-owner change require fresh approval. Disable clears this trust decision.
            </Text>
          </ModalBody>
          <ModalFooter gap="3">
            <Button ref={denyRef} onClick={() => setApproval(null)} isDisabled={!!pending}>
              Deny
            </Button>
            <Button
              colorScheme="green"
              isLoading={!!pending}
              isDisabled={!isRoomOwner}
              onClick={() => {
                if (approval) {
                  void changeActivation(approval, true);
                }
              }}
            >
              Enable
            </Button>
          </ModalFooter>
        </ModalContent>
      </Modal>

      <VStack
        style={{ maxHeight: 'min(300px, 50svh)' }}
        m={0}
        spacing={1}
        overflow="auto"
        css={{
          '&::-webkit-scrollbar': {
            width: '6px',
          },
          '&::-webkit-scrollbar-track': {
            width: '6px',
          },
          '&::-webkit-scrollbar-thumb': {
            background: gripColor,
            borderRadius: 'md',
          },
        }}
      >
        {plugins.map((plugin) => {
          const manifest = plugin.data.package?.manifest;
          const enabled = isPluginEnabled(plugin, props.boardId);
          const available = manifest?.apiVersion === 1;
          const autoApproval = plugin.data.boardAutoApprovals?.[props.boardId];
          const hasAutoApproval = !!autoApproval && autoApproval.ownerId === room?.data.ownerId;

          let activationColor: string;
          let activationLabel: string;

          if (!available) {
            activationColor = 'orange';
            activationLabel = 'Unavailable';
          } else if (enabled) {
            activationColor = 'green';
            activationLabel = 'Enabled';
          } else {
            activationColor = 'gray';
            activationLabel = 'Disabled';
          }

          return (
            <Box key={plugin._id} width="100%" p="2">
              <Text fontWeight="bold">{manifest?.name ?? plugin.data.name}</Text>
              <Badge colorScheme={activationColor}>
                {activationLabel}
                    </Badge>
              <Text fontSize="xs" my="1">
                {manifest?.description ?? plugin.data.description}
              </Text>
              {!available && (
                <Text fontSize="xs">Upload an API v1 manifest package before enabling.</Text>
              )}
              {available && (
                <>
                  <HStack my="1" flexWrap="wrap">
                    {isRoomOwner ? (
                      <>
                        <Button size="xs" isDisabled={!!pending} onClick={() => openApproval(plugin)}>
                          {enabled ? 'Approval settings…' : 'Enable…'}
                        </Button>
                        {(enabled || !!autoApproval) && (
                          <Button
                            size="xs"
                            isDisabled={!!pending}
                            onClick={() => void changeActivation(plugin, false)}
              >
                            {enabled ? 'Disable' : 'Stop auto-approval'}
                          </Button>
                        )}
                      </>
                    ) : (
                      <Text fontSize="xs">Only the room owner can enable or disable plugins.</Text>
                    )}
                  </HStack>
                  {hasAutoApproval && (
                    <Text fontSize="xs">Future uploads are trusted only within the approved capabilities.</Text>
                  )}
                  {enabled && (
                    <Text fontSize="xs">Disabling preserves apps and saved data.</Text>
                  )}
                </>
              )}
            </Box>
            );
          })}
        <PluginActions
          placement="board-menu"
          onActionComplete={props.onActionComplete}
          context={{
            boardId: props.boardId,
            roomId: props.roomId,
            position: props.target,
            selectedAppIds: [],
          }}
        />
        <Divider my="1" />
        <Button onClick={pluginOnOpen} py="1px" m="0" width="100%" size="xs" colorScheme="green">
            Upload
          </Button>
      </VStack>
    </>
  );
}
